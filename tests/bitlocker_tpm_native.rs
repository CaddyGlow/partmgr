//! Opt-in real swtpm command-engine gates; synthetic objects are not Windows evidence.
#![cfg(all(feature = "bitlocker-tpm", unix))]

use partmgr::{
    bitlocker::{BitLockerVolume, KeyEvidence, Limits, MetadataSelection},
    bitlocker_swtpm::{ImportConfig, ImportedSwtpm, Startup},
    bitlocker_tpm::{Tpm2Protector, UnsealedVmk},
    bitlocker_tpm_host::{Tpm2Provider, UnixCommandTransport, UnsealRequest},
    fs_core::{Budget, Cancellation, Resources},
};
use sha2::{Digest, Sha256};
use std::{fs, path::PathBuf, sync::Arc, time::Duration};
use zeroize::Zeroizing;

fn setting(name: &str) -> PathBuf {
    std::env::var_os(name)
        .unwrap_or_else(|| panic!("missing {name}"))
        .into()
}

#[test]
#[ignore = "requires swtpm and the synthetic fixture generated by integration/bitlocker/swtpm-gate.py"]
fn imported_swtpm_policy_auth_value_unseals_and_preserves_source() {
    let root = setting("PARTMGR_BITLOCKER_TPM_FIXTURE");
    let executable = setting("PARTMGR_SWTPM");
    let source = root.join("source/state");
    let before = Sha256::digest(fs::read(source.join("tpm2-00.permall")).unwrap());
    let directory = tempfile::tempdir().unwrap();
    let instance_directory = directory.path().join("instance");
    let mut instance = ImportedSwtpm::import(ImportConfig {
        executable: &executable,
        source_state: &source,
        instance_directory: &instance_directory,
        startup: Startup::Clear,
        timeout: Duration::from_secs(5),
    })
    .unwrap();
    let public = fs::read(root.join("sealed.pub")).unwrap();
    let private = Zeroizing::new(fs::read(root.join("sealed.priv")).unwrap());
    let expected = Zeroizing::new(fs::read(root.join("secret.bin")).unwrap());
    let digest: [u8; 32] = Sha256::digest([0; 64]).into();
    let mut datum = vec![0x2e, 1, 0, 0, 6, 0, 5, 0, 0x80, 8, 0, 0];
    datum.extend_from_slice(&private);
    datum.extend_from_slice(&public);
    datum.extend_from_slice(&[0, 32]);
    datum.extend_from_slice(&digest);
    datum.extend_from_slice(&[3, 0x80, 8, 0]);
    let parsed = Tpm2Protector::parse(0x0100, &datum).unwrap();
    let mut nonce = [0; 32];
    std::io::Read::read_exact(&mut fs::File::open("/dev/urandom").unwrap(), &mut nonce).unwrap();
    let request = UnsealRequest {
        public: parsed.public_blob(),
        private: parsed.private_blob(),
        parent_handle: 0x8100_0001,
        nonce_caller: &nonce,
        pcr_selection: &[0, 0, 0, 1, 0, 0x0b, 3, 0x80, 8, 0],
        pcr_digest: Some(&digest),
        policy_or: &[],
        policy_auth_value: true,
    };
    let resources = Resources {
        memory: Budget::new(1 << 20),
        cancellation: Cancellation::default(),
    };
    let transport =
        UnixCommandTransport::connect(instance.command_socket(), Duration::from_secs(5)).unwrap();
    let mut provider = Tpm2Provider::new(transport);
    let secret = provider.unseal(&request, &resources).unwrap();
    assert!(
        secret.as_bytes() == expected.as_slice(),
        "unsealed payload mismatch"
    );
    let vmk = UnsealedVmk::parse(secret.as_bytes()).unwrap();
    let inspected = synthetic_volume(&datum, vmk.as_bytes(), false, &resources);
    std::io::Read::read_exact(&mut fs::File::open("/dev/urandom").unwrap(), &mut nonce).unwrap();
    assert_eq!(
        inspected
            .authenticate_tpm([7; 16], &mut provider, 0x8100_0001, &nonce)
            .unwrap(),
        KeyEvidence::AuthenticatedKeyRecord
    );
    std::io::Read::read_exact(&mut fs::File::open("/dev/urandom").unwrap(), &mut nonce).unwrap();
    let reader = inspected
        .unlock_tpm([7; 16], &mut provider, 0x8100_0001, &nonce)
        .unwrap();
    assert_eq!(reader.key_evidence(), KeyEvidence::AuthenticatedKeyRecord);
    let corrupted = synthetic_volume(&datum, vmk.as_bytes(), true, &resources);
    std::io::Read::read_exact(&mut fs::File::open("/dev/urandom").unwrap(), &mut nonce).unwrap();
    let error = corrupted
        .authenticate_tpm([7; 16], &mut provider, 0x8100_0001, &nonce)
        .unwrap_err();
    assert!(matches!(
        error,
        partmgr::bitlocker::TpmUnlockError::Volume(partmgr::bitlocker::Error {
            kind: partmgr::bitlocker::ErrorKind::AuthenticationFailed,
            ..
        })
    ));
    drop(secret);
    drop(provider);
    instance.shutdown().unwrap();
    assert!(before == Sha256::digest(fs::read(source.join("tpm2-00.permall")).unwrap()));
}

// Synthetic metadata authenticates the full provider -> VMK -> FVEK path. It
// establishes no Windows disk or filesystem interoperability.
fn synthetic_volume(
    datum: &[u8],
    vmk: &[u8; 32],
    corrupt: bool,
    resources: &Resources,
) -> BitLockerVolume {
    use aes::Aes256;
    use ccm::{
        Ccm,
        aead::{AeadInPlace, KeyInit},
        consts::{U12, U16},
    };
    fn w(b: &mut [u8], at: usize, n: u16) {
        b[at..at + 2].copy_from_slice(&n.to_le_bytes());
    }
    fn d(b: &mut [u8], at: usize, n: u32) {
        b[at..at + 4].copy_from_slice(&n.to_le_bytes());
    }
    fn q(b: &mut [u8], at: usize, n: u64) {
        b[at..at + 8].copy_from_slice(&n.to_le_bytes());
    }
    fn entry(kind: u16, value: u16, body: &[u8]) -> Vec<u8> {
        let mut entry = vec![0; 8];
        w(&mut entry, 0, (body.len() + 8) as u16);
        w(&mut entry, 2, kind);
        w(&mut entry, 4, value);
        w(&mut entry, 6, 1);
        entry.extend_from_slice(body);
        entry
    }
    let mut body = vec![0; 28];
    body[..16].fill(7);
    w(&mut body, 26, 0x0100);
    body.extend_from_slice(datum);
    let mut entries = entry(2, 8, &body);
    let mut fvek = Zeroizing::new(vec![0; 44]);
    d(&mut fvek, 0, 44);
    w(&mut fvek, 4, 1);
    d(&mut fvek, 8, 0x8004);
    for (i, byte) in fvek[12..].iter_mut().enumerate() {
        *byte = i as u8;
    }
    let cipher = Ccm::<Aes256, U16, U12>::new_from_slice(vmk).unwrap();
    let tag = cipher
        .encrypt_in_place_detached((&[3; 12]).into(), &[], &mut fvek)
        .unwrap();
    let mut wrapped = vec![3; 12];
    wrapped.extend_from_slice(&tag);
    wrapped.extend_from_slice(&fvek);
    if corrupt {
        wrapped[12] ^= 1;
    }
    entries.extend(entry(3, 5, &wrapped));
    let size = (112 + entries.len()).next_multiple_of(16);
    let mut block = vec![0; size + 8];
    block[..8].copy_from_slice(b"-FVE-FS-");
    w(&mut block, 8, (size / 16) as u16);
    w(&mut block, 10, 2);
    w(&mut block, 12, 4);
    w(&mut block, 14, 4);
    q(&mut block, 16, 1 << 20);
    d(&mut block, 28, 1);
    q(&mut block, 56, 0x40000);
    for (i, offset) in [0x50000, 0x60000, 0x70000].iter().enumerate() {
        q(&mut block, 32 + i * 8, *offset);
    }
    for (at, value) in [
        (64, 48 + entries.len() as u32),
        (68, 1),
        (72, 48),
        (76, 48 + entries.len() as u32),
        (100, 0x8004),
    ] {
        d(&mut block, at, value);
    }
    block[80..96].fill(9);
    block[112..112 + entries.len()].copy_from_slice(&entries);
    let mut crc = !0u32;
    for byte in &block[..size] {
        crc ^= u32::from(*byte);
        for _ in 0..8 {
            crc = (crc >> 1) ^ if crc & 1 != 0 { 0xedb8_8320 } else { 0 };
        }
    }
    w(&mut block, size, 8);
    w(&mut block, size + 2, 1);
    d(&mut block, size + 4, !crc);
    let mut image = vec![0; 1 << 20];
    image[3..11].copy_from_slice(b"-FVE-FS-");
    w(&mut image, 11, 512);
    w(&mut image, 510, 0xaa55);
    image[160..176].copy_from_slice(&[
        0x3b, 0xd6, 0x67, 0x49, 0x29, 0x2e, 0xd8, 0x4a, 0x83, 0x99, 0xf6, 0xa3, 0x39, 0xe3, 0xd0, 1,
    ]);
    for (i, offset) in [0x50000, 0x60000, 0x70000].iter().enumerate() {
        q(&mut image, 176 + 8 * i, *offset as u64);
        image[*offset..*offset + block.len()].copy_from_slice(&block);
    }
    struct Image(Vec<u8>);
    impl partmgr::io::ReadAt for Image {
        fn len(&self) -> u64 {
            self.0.len() as u64
        }
        fn read_exact_at(&self, offset: u64, out: &mut [u8]) -> partmgr::io::Result<()> {
            let at = usize::try_from(offset).map_err(|_| std::io::Error::other("offset"))?;
            let bytes = self
                .0
                .get(at..at + out.len())
                .ok_or_else(|| std::io::Error::other("bounds"))?;
            out.copy_from_slice(bytes);
            Ok(())
        }
    }
    BitLockerVolume::inspect(
        Arc::new(Image(image)),
        MetadataSelection::RequireAgreement,
        Limits::default(),
        resources,
    )
    .unwrap()
}

#[test]
#[ignore = "requires captured Windows metadata and matching stopped swtpm state"]
fn windows_native_object_loads_but_cold_pcr_policy_is_rejected() {
    let root = setting("PARTMGR_BITLOCKER_TPM_EVIDENCE");
    let source_state = setting("PARTMGR_BITLOCKER_TPM_STATE");
    let executable = setting("PARTMGR_SWTPM");
    let length: u64 = std::env::var("PARTMGR_BITLOCKER_LENGTH")
        .unwrap()
        .parse()
        .unwrap();
    let volume = captured_volume(&root, length);
    let identifier = volume
        .protectors()
        .find(|p| p.protection_type == 0x100)
        .unwrap()
        .identifier;
    assert_eq!(volume.tpm_protector(identifier).unwrap().pcr_mask(), 0x880);
    let directory = tempfile::tempdir().unwrap();
    let instance_directory = directory.path().join("instance");
    let before = Sha256::digest(fs::read(source_state.join("tpm2-00.permall")).unwrap());
    let mut instance = ImportedSwtpm::import(ImportConfig {
        executable: &executable,
        source_state: &source_state,
        instance_directory: &instance_directory,
        startup: Startup::Clear,
        timeout: Duration::from_secs(5),
    })
    .unwrap();
    let mut provider = Tpm2Provider::new(
        UnixCommandTransport::connect(instance.command_socket(), Duration::from_secs(5)).unwrap(),
    );
    let mut nonce = [0; 32];
    std::io::Read::read_exact(&mut fs::File::open("/dev/urandom").unwrap(), &mut nonce).unwrap();
    let error = volume
        .authenticate_tpm(identifier, &mut provider, 0x8100_0001, &nonce)
        .unwrap_err();
    let partmgr::bitlocker::TpmUnlockError::Provider(error) = error else {
        panic!("expected provider policy failure");
    };
    assert_eq!(
        error.kind,
        partmgr::bitlocker_tpm_host::ErrorKind::PolicyFailed,
        "{error:?}"
    );
    assert_eq!(
        error.command, 0x17f,
        "Load and PolicyAuthValue must succeed before PolicyPCR rejects cold state"
    );
    assert!(!error.cleanup_required);
    assert!(!provider.uncertain_completion());
    drop(provider);
    instance.shutdown().unwrap();
    assert!(before == Sha256::digest(fs::read(source_state.join("tpm2-00.permall")).unwrap()));
}

#[test]
#[ignore = "requires a Windows fixture and an exclusive matching TPM endpoint in its unseal PCR state"]
fn windows_native_tpm_authenticates_wrapped_fvek() {
    let root = setting("PARTMGR_BITLOCKER_TPM_EVIDENCE");
    let socket = setting("PARTMGR_BITLOCKER_TPM_SOCKET");
    let length = std::env::var("PARTMGR_BITLOCKER_LENGTH")
        .unwrap()
        .parse()
        .unwrap();
    let parent = std::env::var("PARTMGR_BITLOCKER_TPM_PARENT").unwrap();
    let parent = u32::from_str_radix(parent.trim_start_matches("0x"), 16).unwrap();
    let volume = captured_volume(&root, length);
    let identifiers: Vec<_> = volume
        .protectors()
        .filter(|p| p.protection_type == 0x100)
        .map(|p| p.identifier)
        .collect();
    assert_eq!(
        identifiers.len(),
        1,
        "fixture must select exactly one TPM-only protector"
    );
    let mut provider =
        Tpm2Provider::new(UnixCommandTransport::connect(&socket, Duration::from_secs(5)).unwrap());
    let mut nonce = [0; 32];
    std::io::Read::read_exact(&mut fs::File::open("/dev/urandom").unwrap(), &mut nonce).unwrap();
    assert_eq!(
        volume
            .authenticate_tpm(identifiers[0], &mut provider, parent, &nonce)
            .unwrap(),
        KeyEvidence::AuthenticatedKeyRecord
    );
    assert!(!provider.uncertain_completion());
    // This known system fixture has an unsupported used-space-only mapping.
    // Authentication must not turn that into an advertised reader capability.
    assert!(matches!(
        volume.read_support().unwrap(),
        partmgr::bitlocker::ReadSupport::Unsupported(_)
    ));
}

fn captured_volume(root: &std::path::Path, length: u64) -> BitLockerVolume {
    let boot = fs::read(root.join("encrypted-boot.bin")).unwrap();
    let offsets: Vec<u64> = (0..3)
        .map(|i| u64::from_le_bytes(boot[176 + i * 8..184 + i * 8].try_into().unwrap()))
        .collect();
    let mut regions = vec![(0, boot)];
    for offset in offsets {
        regions.push((
            offset,
            fs::read(root.join(format!("metadata-{offset}.bin"))).unwrap(),
        ));
    }
    struct Captured {
        length: u64,
        regions: Vec<(u64, Vec<u8>)>,
    }
    impl partmgr::io::ReadAt for Captured {
        fn len(&self) -> u64 {
            self.length
        }
        fn read_exact_at(&self, offset: u64, out: &mut [u8]) -> partmgr::io::Result<()> {
            for (start, bytes) in &self.regions {
                if let Some(relative) = offset.checked_sub(*start)
                    && let Ok(relative) = usize::try_from(relative)
                    && let Some(end) = relative.checked_add(out.len())
                    && let Some(data) = bytes.get(relative..end)
                {
                    out.copy_from_slice(data);
                    return Ok(());
                }
            }
            Err(partmgr::io::Error::other("read outside captured metadata"))
        }
    }
    let resources = Resources {
        memory: Budget::new(16 << 20),
        cancellation: Cancellation::default(),
    };
    BitLockerVolume::inspect(
        Arc::new(Captured { length, regions }),
        MetadataSelection::RequireAgreement,
        Limits::default(),
        &resources,
    )
    .unwrap()
}
